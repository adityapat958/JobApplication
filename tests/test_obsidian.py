def _git(*args, cwd):
    return subprocess.run(["git", "-c", "core.quotepath=false", *args], cwd=cwd, capture_output=True, text=True, check=True).stdout


def _init_repo(path: Path):
    _git("init", "-q", "-b", "main", cwd=path)
    _git("config", "user.name", "Test", cwd=path)
    _git("config", "user.email", "test@example.com", cwd=path)
    (path / "other.md").write_text("mine")
    _git("add", "other.md", cwd=path)
    _git("commit", "-qm", "init", cwd=path)


