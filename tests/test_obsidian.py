    for jid in (a["id"], b["id"]):
        assert c.find(db.get_job(conn, jid)) is not None
    assert c.find(a) != c.find(b)
    assert ob.safe_name('a/b\\c:d*e?f"g<h>i|j#k^l[m]n') == "abcdefghijklmn"
    assert ob.safe_name("  ..  ") == "Untitled"
    assert ob.safe_name(unicodedata.normalize("NFD", "Blåbær")) == "Blåbær"  # stored NFC
    assert len(ob.safe_name("x" * 200)) == 60


