def test_sync_idempotent_and_dry_run(profile, tmp_path):
    cfg, vault = make_cfg(tmp_path)
    conn = db.connect()
    for i in range(3):
        add(conn, f"20{i}", title=f"Analyst {i}")
    c = conn_for(cfg)
    dry = c.sync(conn, dry_run=True)
    assert len(dry["created"]) == 3 and len(dry["generated"]) == 2
    assert not (vault / "Jobs").exists()
    first = c.sync(conn)
    assert len(first["created"]) == 3 and len(first["generated"]) == 2
    before = files(vault)
    second = conn_for(cfg).sync(conn)
    assert second["created"] == second["updated"] == second["generated"] == [] and second["unchanged"] == 3
    assert files(vault) == before
    dash = (vault / "Jobs" / "_Dashboard.md").read_text()
    assert dash.startswith("<!-- Generated by JobApplication") and "edits to this file are overwritten" in dash
    assert "| new | 3 |" in dash and "[[Jobs/Full-Time/Fjordline Analytics — Analyst 0\\|" in dash
    today = (vault / "Jobs" / "_New Today.md").read_text()
    assert "**3 new roles** | 3 full-time" in today


