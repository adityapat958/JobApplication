def test_filename_collisions_and_unsafe_chars(profile, tmp_path):
    cfg, vault = make_cfg(tmp_path)
    conn = db.connect()
    a = add(conn, "701", company="Nordlys AS", title="Analytiker: Økonomi/Finans 🚀")
    b = add(conn, "702", company="Nordlys AS", title="Analytiker: Økonomi/Finans 🚀")
