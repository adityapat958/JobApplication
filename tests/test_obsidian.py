def make_cfg(tmp_path, **opts):
    vault = tmp_path / "vault"
    (vault / ".obsidian").mkdir(parents=True, exist_ok=True)
    return config.parse({"connectors": {"obsidian": {"enabled": True, "vault": str(vault), **opts}}}), vault


def add(conn, sid, company="Fjordline Analytics", title="Data Analyst", source="linkedin", match=62.4,
        job_type="fulltime", **kw):
    jp = JobPosting(source=source, source_id=sid, title=title, company=company, location="Oslo, Norway",
                    url=f"https://jobs.example.com/{sid}", job_type=job_type, **kw)
    jid, _ = db.upsert_job(conn, jp, ts=TS)
    if match is not None:
        db.set_match(conn, jid, match, ["Python", "SQL", "C++"], ["Tableau"])
    return db.get_job(conn, jid)


def conn_for(cfg, **kw):
    return ob.ObsidianConnector(cfg, clock=CLOCK, **kw)


def files(root: Path) -> dict:
    return {str(p.relative_to(root)): p.read_bytes() for p in sorted(root.rglob("*")) if p.is_file()}


