def test_older_note_status_is_taken_over_once(profile, tmp_path):
    cfg, vault = make_cfg(tmp_path)
    conn = db.connect()
    j = add(conn, "d01")
    d = vault / "Jobs" / "Full-Time"
    d.mkdir(parents=True)
    old = ('---\ncompany: "Fjordline Analytics"\ntitle: "Data Analyst"\nstatus: "applied"\n'
           "date_applied: 2026-01-20\n---\n\n- [x] Applied\n")
    p = d / "Fjordline Analytics — Data Analyst.md"
    p.write_text(old)
    connectors.notify_added(cfg, j)  # outside sync: left alone (no DB to update from here)
    assert p.read_text() == old
    dry = conn_for(cfg).sync(conn, dry_run=True)
    assert dry["imported"] == [(j["id"], "applied")] and db.get_job(conn, j["id"])["status"] == "new"
    res = conn_for(cfg).sync(conn)
    assert res["imported"] == [(j["id"], "applied")] and res["updated"] == [p]
    assert db.get_job(conn, j["id"])["status"] == "applied"
    text = p.read_text()
    assert 'status: "applied"' in text and "date_applied: 2026-01-20" in text and f'job_id: "{j["id"]}"' in text
    assert conn_for(cfg).sync(conn)["updated"] == []


