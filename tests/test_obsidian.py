# ── poll integration, isolation ───────────────────────────
def li_cfg(tmp_path, **ob_opts):
    vault = tmp_path / "vault"
    (vault / ".obsidian").mkdir(parents=True, exist_ok=True)
    return config.parse({
        "sources": {"linkedin": {"enabled": True, "max_pages": 1, "searches": [{"keywords": "analyst"}]}},
        "filters": {"title_include": ["analyst", "*analytiker"], "title_exclude": ["senior"]},
        "connectors": {"obsidian": {"vault": str(vault), **ob_opts}},
    }), vault


def li_http():
    return mock_http({"seeMoreJobPostings": fixture_text("linkedin", "search_page0.html"),
                      "jobPosting/4473638585": fixture_text("linkedin", "job_4473638585.html")})


def test_poll_writes_notes_for_visible_jobs(profile, tmp_path):
    cfg, vault = li_cfg(tmp_path, enabled=True)
    conn = db.connect()
    res = run_poll(cfg, conn, http=li_http())
    notes = [p for p in (vault / "Jobs").rglob("*.md") if not p.name.startswith("_")]
    assert len(notes) == res[0].kept == len(db.list_jobs(conn)) > 0
    assert (vault / "Jobs" / "_Dashboard.md").exists() and (vault / "Jobs" / "_New Today.md").exists()
    ids = {ob.note_state(p.read_text())["job_id"] for p in notes}
    assert ids == {j["id"] for j in db.list_jobs(conn)}
    st = connectors.load_state("obsidian")
    assert st["since"] and st["last_sync"]
    before = files(vault)
    run_poll(cfg, conn, http=li_http())
    after = files(vault)
    assert {k for k in after if after[k] != before.get(k)} <= {"Jobs/_Dashboard.md", "Jobs/_New Today.md"}
    checks = connectors.doctor_checks(cfg)
    assert any(c.name == "Connector: obsidian notes" and f"{len(notes)} note(s)" in c.detail for c in checks)


