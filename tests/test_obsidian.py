# ── updates keep the user's text ──────────────────────────
def test_update_preserves_user_text_unknown_keys_and_order(profile, tmp_path):
    cfg, vault = make_cfg(tmp_path)
    conn = db.connect()
    j = add(conn, "401")
    c = conn_for(cfg)
    c.on_job_added(j)
    p = next((vault / "Jobs").rglob("*.md"))
    text = p.read_text()
    # the user: own key at the top, Obsidian-style block list, notes, why
    text = text.replace("---\ncompany:", "---\nrating: 5\ncompany:", 1)
    text = text.replace('matched: ["Python", "SQL", "C++"]', "matched:\n  - Python\n  - SQL\n  - C++")
    text = text.replace("_Add notes here after reviewing the job description._", "Called the recruiter: great team.\nstatus: not this")
    text = text.replace("_What makes this a good fit for your background?_", "- [ ] Applied (my own list)")
    text += "\nextra line at the end\n"
    p.write_text(text)
    assert c.upsert(j) is None  # same values in another YAML style → no rewrite
    j2 = db.set_status(conn, j["id"], "applied")
    c.on_job_updated(j2, {"status": ["new", "applied"]})
    new = p.read_text()
    changed = [(a, b) for a, b in zip(text.splitlines(), new.splitlines()) if a != b]
    assert len(new.splitlines()) == len(text.splitlines())
    assert changed == [('status: "new"', 'status: "applied"'),
                       ("date_applied:", f"date_applied: {ob._local_date(j2['done_at']).isoformat()}"),
                       ("- [ ] Applied", "- [x] Applied")]
    assert new.splitlines()[1] == "rating: 5"
    # match change: only those keys
    db.set_match(conn, j["id"], 80, ["Python"], [])
    c.on_job_updated(db.get_job(conn, j["id"]), {"built": "x.pdf"})
    fm = ob.parse_fm(ob.split_note(p.read_text())[0])
    assert fm["match"] == 80 and fm["matched"] == ["Python"] and fm["missing"] == [] and fm["rating"] == 5
    assert "Called the recruiter: great team.\nstatus: not this" in p.read_text()
    # user changes date_applied → kept while still applied
    p.write_text(p.read_text().replace(f"date_applied: {fm['date_applied']}", "date_applied: 2026-01-15"))
    c.upsert(db.get_job(conn, j["id"]))
    assert "date_applied: 2026-01-15" in p.read_text()


