"""Obsidian connector: one Markdown note per job in your vault (off unless connectors.obsidian.enabled).

Notes are found by `job_id` in their frontmatter (so renamed/moved notes still update), else by file name.
Only the managed frontmatter keys and the "Applied" checkbox are ever changed in an existing note; your own
text and any other frontmatter keys stay exactly as they are. All writes are atomic (temp file + rename).
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import tempfile
import unicodedata
from datetime import date, datetime, timezone
from pathlib import Path

import yaml

from ..db import DONE_STATUSES, now
from ..models import STATUSES
from ..text import parse_iso

NAME = "obsidian"
MANAGED = ("status", "date_applied", "job_id", "match", "matched", "missing", "url", "also_on")
GENERATED = ("_Dashboard.md", "_New Today.md")
GEN_HEADER = ("<!-- Generated by JobApplication — edits to this file are overwritten. "
              "Write in the job notes instead. -->\n"
              "> [!info] Generated by JobApplication — edits to this file are overwritten on every search.\n")
_FM = re.compile(r"\A---[ \t]*\n(.*?\n)?---[ \t]*(?:\n|\Z)", re.S)
_KEY = re.compile(r"^([^\s#\-][^:]*?):(?:[ \t]|$)")
_APPLIED = re.compile(r"(?m)^([ \t]*[-*] \[)([ xX])(\] Applied[ \t]*)$")


class ObsidianError(Exception):
    pass


# ── helpers ──────────────────────────────────────────────
def safe_name(s: str) -> str:
    """File-safe note name (same rule as the old exporter, plus control chars / leading dots)."""
    s = unicodedata.normalize("NFC", s or "")
    s = re.sub(r'[\\/*?:"<>|#^[\]\x00-\x1f\x7f]', "", s)
    s = re.sub(r"\s+", " ", s).strip()[:60].strip().strip(".").strip()
    return s or "Untitled"


def _key(name: str) -> str:
    return unicodedata.normalize("NFC", name).casefold()


def _local_date(iso: str | None) -> date | None:
    dt = parse_iso(iso) if iso else None
    return dt.astimezone().date() if dt else None


def _q(s) -> str:
    return json.dumps("" if s is None else str(s), ensure_ascii=False)


def _render(v) -> str:
    if v is None or v == "":
        return ""
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, date):
        return v.isoformat()
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(_q(x) for x in v) + "]"
    return _q(v)


def _norm(v):
    """Compare values semantically (so Obsidian reformatting a list or quotes never causes a rewrite)."""
    if v is None or v == "" or v == []:
        return None
    if isinstance(v, bool):
        return v
    if isinstance(v, (int, float)):
        return float(v)
    if isinstance(v, (date, datetime)):
        return v.isoformat()[:10]
    if isinstance(v, (list, tuple)):
        return [str(x) for x in v]
    return str(v)


def split_note(text: str) -> tuple[str | None, str]:
    """(frontmatter text without the --- lines, body). frontmatter None if the note has none."""
    m = _FM.match(text)
    if not m:
        return None, text
    return m.group(1) or "", text[m.end():]


def parse_fm(fm: str | None) -> dict:
    if not fm:
        return {}
    try:
        d = yaml.safe_load(fm)
        return d if isinstance(d, dict) else {}
    except yaml.YAMLError:
        out = {}
        for line in fm.splitlines():
            m = re.match(r'^(status|job_id):\s*"?([^"\n]*)"?\s*$', line)
            if m:
                out[m[1]] = m[2].strip()
        return out


def _entries(fm: str) -> list[list]:
    """Split frontmatter into [key, block] entries; continuation lines (lists, indented) stay with their key."""
    out: list[list] = []
    for line in fm.splitlines(keepends=True):
        m = _KEY.match(line)
        if m or not out or not line.strip() or line.startswith("#"):
            out.append([m.group(1).strip() if m else None, line])
        else:
            out[-1][1] += line
    return out


def set_keys(fm: str, values: dict, old: dict) -> str:
    """Rewrite only the entries in `values` whose meaning changed; append missing ones. Order kept."""
    entries = _entries(fm)
    seen = set()
    for e in entries:
        k = e[0]
        if k in values and k not in seen:
            seen.add(k)
            if _norm(old.get(k)) != _norm(values[k]):
                e[1] = (f"{k}: {_render(values[k])}".rstrip() + "\n")
    text = "".join(e[1] for e in entries)
    if text and not text.endswith("\n"):
        text += "\n"
    for k, v in values.items():
        if k not in seen:
            text += f"{k}: {_render(v)}".rstrip() + "\n"
    return text


def applied_box(body: str) -> bool | None:
    m = _APPLIED.search(body)
    return None if not m else m.group(2) in "xX"


def set_applied_box(body: str, ticked: bool) -> str:
    return _APPLIED.sub(lambda m: m.group(1) + ("x" if ticked else " ") + m.group(3), body, count=1)


def _cell(s) -> str:
    return str(s or "").replace("|", "\\|").replace("\n", " ")


def _link_target(url: str) -> str:
    return f"<{url}>" if re.search(r"[\s()<>]", url) else url


def atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=".jobapp-", suffix=".tmp", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def source_label(name: str) -> str:
    try:
        from ..sources import get
        return get(name).label
    except Exception:  # noqa: BLE001
        return name or ""


# ── note content ─────────────────────────────────────────
def managed_values(job: dict, old: dict | None = None) -> dict:
    old = old or {}
    status = job.get("status") or "new"
    applied = None
    if status in DONE_STATUSES:
        applied = _norm(old.get("date_applied")) or _local_date(job.get("done_at")) or date.today()
        if isinstance(applied, str):
            applied = date.fromisoformat(applied) if re.fullmatch(r"\d{4}-\d{2}-\d{2}", applied) else applied
    pct = job.get("match_pct")
    return {
        "status": status,
        "date_applied": applied,
        "job_id": job["id"],
        "match": None if pct is None else int(round(pct)),
        "matched": list(job.get("matched") or []),
        "missing": list(job.get("missing") or []),
        "url": job.get("apply_url") or job.get("url") or None,
        "also_on": [a["source"] for a in job.get("also_on") or []],
    }


def render_note(job: dict, stamp: datetime | None = None) -> str:
    stamp = stamp or datetime.now()
    raw = job.get("raw") if isinstance(job.get("raw"), dict) else {}
    company, title = job.get("company") or "", job.get("title") or ""
    jtype, src = job.get("job_type") or "", source_label(job.get("source") or "")
    found = _local_date(job.get("first_seen_at")) or stamp.date()
    tier = raw.get("tier")
    v = managed_values(job)
    tags = ["job"] + ([jtype] if jtype else []) + ([str(tier).split()[-1].lower()] if tier else [])
    fm = [f"company: {_q(company)}", f"title: {_q(title)}", f"location: {_q(job.get('location'))}",
          f"type: {_q(jtype)}", f"source: {_q(src)}"]
    if tier:
        fm.append(f"tier: {_q(tier)}")
    fm += [f"status: {_q(v['status'])}", f"date_found: {found.isoformat()}",
           f"date_applied: {_render(v['date_applied'])}".rstrip(), f"tags: [{', '.join(tags)}]"]
    fm += [f"{k}: {_render(v[k])}".rstrip() for k in MANAGED if k not in ("status", "date_applied")]
    url = v["url"]
    link = f"[🔗 Apply Now]({_link_target(url)})" if url else "_Link not available — search manually_"
    rows = [f"| 📍 Location | {_cell(job.get('location'))} |"]
    if tier:
        rows.append(f"| 🏢 Company tier | {_cell(tier)} |")
    rows += [f"| 📂 Source | {_cell(src)} |", f"| 📆 Found | {found.isoformat()} |"]
    salary, term = raw.get("salary"), raw.get("term")
    rows.append(f"| 💰 Salary | {_cell(salary)} |" if salary else "")
    rows.append(f"| 📅 Term | {_cell(term)} |" if term else "")
    box = "x" if v["status"] in DONE_STATUSES else " "
    return ("---\n" + "\n".join(fm) + "\n---\n\n"
            f"# {company} — {title}\n\n"
            "| Field    | Value |\n|----------|-------|\n" + "\n".join(rows) + "\n\n"
            f"## 🔗 Apply\n\n{link}\n\n"
            "## 📋 Status\n\n- [ ] Reviewed JD\n- [ ] Tailored resume\n- [ ] Wrote cover letter\n"
            f"- [{box}] Applied\n- [ ] Followed up\n\n"
            "## 📝 Notes\n\n_Add notes here after reviewing the job description._\n\n"
            "## 🎯 Why This Role\n\n_What makes this a good fit for your background?_\n\n"
            f"---\n*Auto-generated by JobApplication · {stamp.strftime('%Y-%m-%d %H:%M')}*\n")


def update_note(text: str, job: dict) -> str:
    """Return the note with managed keys + Applied box set from the job; everything else untouched."""
    fm, body = split_note(text)
    if fm is None:
        raise ObsidianError("note has no frontmatter")
    old = parse_fm(fm)
    vals = managed_values(job, old)
    new_fm = set_keys(fm, vals, old)
    box = applied_box(body)
    want = vals["status"] in DONE_STATUSES
    new_body = set_applied_box(body, want) if box is not None and box != want else body
    if new_fm == fm and new_body == body:
        return text
    return "---\n" + new_fm + "---\n" + new_body


def note_job_id(text: str) -> str | None:
    """Fast path (no YAML parse): the job_id in a note's frontmatter."""
    fm, _ = split_note(text)
    m = re.search(r"""(?m)^job_id:[ \t]*["']?([^"'\s#]+)""", fm or "")
    return m.group(1) if m else None


def note_state(text: str) -> dict:
    fm, body = split_note(text)
    d = parse_fm(fm)
    return {"job_id": note_job_id(text),
            "status": str(d.get("status") or "").strip().lower() or None,
            "applied": applied_box(body)}


# ── the connector ────────────────────────────────────────
class ObsidianConnector:
    name = NAME

    def __init__(self, cfg, *, clock=None):
        self.cfg = cfg
        self.oc = cfg.connectors.obsidian
        self.vault = cfg.resolve(self.oc.vault)
        self.root = self.vault / self.oc.folder
        self.two_way = self.oc.two_way
        self.clock = clock or datetime.now
        self.dry_run = False
        self.changes: list[tuple[str, Path]] = []
        self._by_id: dict[str, Path] | None = None
        self._by_name: dict[str, list[Path]] = {}
        self._claimed: set[Path] = set()  # notes given a job_id in this run (matters for --dry-run)
        self._importing = False
        self.imported: list[tuple[str, str]] = []  # (job id, status) taken over from older notes

    # index ------------------------------------------------
    def _check_vault(self) -> None:
        if not self.vault.is_dir():
            raise ObsidianError(f"vault folder not found: {self.vault}")

    def notes(self):
        if not self.root.is_dir():
            return
        for p in sorted(self.root.rglob("*.md")):
            rel = p.relative_to(self.root)
            if any(part.startswith(".") for part in rel.parts) or (len(rel.parts) == 1 and p.name in GENERATED):
                continue
            yield p

    def scan(self) -> None:
        self._by_id, self._by_name, self._claimed = {}, {}, set()
        for p in self.notes():
            self._by_name.setdefault(_key(p.stem), []).append(p)
            try:
                jid = note_job_id(p.read_text(encoding="utf-8", errors="replace"))
            except OSError:
                continue
            if jid and jid not in self._by_id:
                self._by_id[jid] = p

    def _ids(self) -> dict[str, Path]:
        if self._by_id is None:
            self.scan()
        return self._by_id

    def find(self, job: dict) -> Path | None:
        jid = job["id"]
        p = self._ids().get(jid)
        if p is not None:
            if p.exists():
                if note_job_id(p.read_text(encoding="utf-8", errors="replace")) == jid or (self.dry_run and p in self._claimed):
                    return p
            elif self.dry_run and p in self._claimed:
                return p  # created in this dry run (not on disk)
            self.scan()  # renamed/moved since we looked
            p = self._by_id.get(jid)
            if p is not None:
                return p
        for c in self._by_name.get(_key(self._stem(job)), []):
            if c.exists() and c not in self._claimed:
                text = c.read_text(encoding="utf-8", errors="replace")
                if split_note(text)[0] is not None and not note_job_id(text):
                    return c  # an older note for this job without an id: adopt it
        return None

    @staticmethod
    def _stem(job: dict) -> str:
        return safe_name(f"{job.get('company') or ''} — {job.get('title') or ''}")

    def _subdir(self, job: dict) -> Path:
        sub = self.oc.subfolders
        t = job.get("job_type") or ""
        return self.root / {"internship": sub.internship, "parttime": sub.parttime}.get(t, sub.fulltime)

    def _new_path(self, job: dict) -> Path:
        d, stem = self._subdir(job), self._stem(job)
        for cand in (stem, f"{stem} ({job['id'][:6]})", f"{stem} ({job['id']})"):
            p = d / f"{cand}.md"
            taken = p.exists() or any(q.parent == d for q in self._by_name.get(_key(cand), []))
            if not taken:
                return p
        raise ObsidianError(f"no free file name for {stem}")

    # writing ----------------------------------------------
    def _write(self, path: Path, text: str, action: str) -> None:
        self.changes.append((action, path))
        if not self.dry_run:
            atomic_write(path, text)

    def eligible(self, job: dict) -> bool:
        if self.oc.only_visible and (job.get("hidden") or job.get("duplicate_of")):
            return False
        if self.oc.min_match and (job.get("status") or "new") == "new" \
                and (job.get("match_pct") or 0) < self.oc.min_match:
            return False
        return True

    def upsert(self, job: dict, *, create: bool = True) -> str | None:
        """Write/refresh the job's note. Returns 'created' / 'updated' / None (no change)."""
        self._check_vault()
        p = self.find(job)
        if p is None:
            if not create:
                return None
            p = self._new_path(job)
            self._write(p, render_note(job, self.clock()), "created")
            self._by_id[job["id"]] = p
            self._by_name.setdefault(_key(p.stem), []).append(p)
            self._claimed.add(p)
            return "created"
        self._by_id[job["id"]] = p
        self._claimed.add(p)
        if self.dry_run and any(q == p and a == "created" for a, q in self.changes):
            return None
        text = p.read_text(encoding="utf-8")
        if not note_job_id(text) and (job.get("status") or "new") == "new":
            # An older note (no job_id yet) that already says applied/interview/…: take its status over once.
            want = effective_status(note_state(text), "new")
            if want and want != "new":
                if not self._importing:
                    self._claimed.discard(p)
                    self._by_id.pop(job["id"], None)
                    return None  # left for `sync`, which can update the database too
                job = dict(job, status=want, done_at=None)
                self.imported.append((job["id"], want))
        new = update_note(text, job)
        if new == text:
            return None
        self._write(p, new, "updated")
        return "updated"

    # Connector protocol -----------------------------------
    def on_job_added(self, job: dict) -> None:
        if self.eligible(job):
            self._ensure_since(job.get("first_seen_at"))
            self.upsert(job)

    def _ensure_since(self, ts: str | None) -> None:
        """Remember when notes started, so a later poll can catch up on notes that failed to write
        (without back-filling everything you had before turning the connector on)."""
        if getattr(self, "_since_ok", False):
            return
        from . import load_state, save_state
        st = load_state(NAME)
        if not st.get("since"):
            st["since"] = min(ts or now(), now())
            save_state(NAME, st)
        self._since_ok = True

    def on_job_updated(self, job: dict, changes: dict) -> None:
        self._check_vault()
        p = self.find(job)
        if self.two_way and p is not None and "status" in changes and not changes.get("conflict"):
            st = note_state(p.read_text(encoding="utf-8", errors="replace"))
            old, new = (list(changes["status"]) + [None, None])[:2]
            note = effective_status(st, old)
            if note and note not in (old, new):
                from . import record_conflict
                record_conflict(NAME, job, note, new)
        if p is not None or self.eligible(job):
            self.upsert(job)

    def pull(self) -> list[dict]:
        """Status as written in each note (frontmatter + Applied checkbox) and when the note last changed."""
        self._check_vault()
        self.scan()
        out = []
        for jid, p in self._by_id.items():
            try:
                st = note_state(p.read_text(encoding="utf-8", errors="replace"))
                mt = datetime.fromtimestamp(p.stat().st_mtime, timezone.utc).replace(microsecond=0)
            except OSError:
                continue
            out.append({"id": jid, "status": st["status"], "applied": st["applied"],
                        "changed_at": mt.isoformat(), "note": str(p.relative_to(self.vault))})
        return out

    # batch ------------------------------------------------
    def sync(self, conn, *, create_all: bool = True, dry_run: bool = False) -> dict:
        """Notes for eligible jobs (all of them, or only those seen since the connector was turned on) and
        refresh every existing note; then the dashboard notes."""
        from .. import db
        from . import load_state, save_state
        self._check_vault()
        self.dry_run, self.changes, self.imported, self._importing = dry_run, [], [], True
        state = load_state(NAME)
        since = state.get("since")
        if not since and not dry_run:
            since = state["since"] = now()
        self.scan()
        jobs = db.list_jobs(conn, include_hidden=True, include_duplicates=True)
        unchanged = 0
        try:
            for j in jobs:
                has = j["id"] in self._by_id
                want = self.eligible(j) and (create_all or (since and (j.get("first_seen_at") or "") >= since))
                if not has and not want:
                    continue
                if self.upsert(j, create=want) is None:
                    unchanged += has
        finally:
            self._importing = False
        if self.imported and not dry_run:
            from . import apply_status
            for jid, status in self.imported:
                apply_status(self.cfg, conn, jid, status, origin=NAME)
            jobs = db.list_jobs(conn, include_hidden=True, include_duplicates=True)
        if self.oc.dashboard_note:
            self.write_dashboards(conn, jobs)
        res = {"created": [p for a, p in self.changes if a == "created"],
               "updated": [p for a, p in self.changes if a == "updated"],
               "generated": [p for a, p in self.changes if a == "generated"], "unchanged": unchanged,
               "imported": list(self.imported)}
        if not dry_run:
            state.update(last_sync=now(), notes=len(self._by_id))
            save_state(NAME, state)
        self.dry_run = False
        return res

    def after_poll(self, conn) -> None:
        self.sync(conn, create_all=False)
        if self.oc.git_push:
            self.git_commit()

    # dashboards -------------------------------------------
    def _wikilink(self, p: Path) -> str:
        rel = p.relative_to(self.vault).with_suffix("").as_posix()
        return f"[[{rel}\\|{p.stem}]]"

    def write_dashboards(self, conn, jobs: list[dict]) -> None:
        today = self.clock().date()
        vis = [j for j in jobs if self.eligible(j)]
        counts = {s: 0 for s in STATUSES}
        for j in vis:
            counts[j["status"]] = counts.get(j["status"], 0) + 1
        top = sorted((j for j in vis if j.get("match_pct") is not None),
                     key=lambda j: (-j["match_pct"], j.get("company") or "", j.get("title") or ""))[:20]
        new = [j for j in vis if _local_date(j.get("first_seen_at")) == today]

        def link(j):
            p = self._by_id.get(j["id"])
            if p is not None:
                return self._wikilink(p)
            u = j.get("apply_url") or j.get("url")
            return f"[Apply]({_link_target(u)})" if u else "—"

        def pct(j):
            return "" if j.get("match_pct") is None else f"{j['match_pct']:.0f}%"

        d = [GEN_HEADER, "# 🚀 Job Search Dashboard", "", f"> Updated: {today.isoformat()}", "",
             "## 📊 Stats", "", "| Status | Count |", "|--------|-------|"]
        d += [f"| {s} | {n} |" for s, n in counts.items()]
        d += [f"| **total** | {len(vis)} |", "", "## 🎯 Top 20 by match", "",
              "| Match | Company | Role | Status | Note |", "|-------|---------|------|--------|------|"]
        d += [f"| {pct(j)} | {_cell(j['company'])} | {_cell((j['title'] or '')[:60])} | {j['status']} | {link(j)} |"
              for j in top]
        d += ["", f"## 🆕 Added today: {len(new)} → [[{(Path(self.oc.folder) / '_New Today').as_posix()}\\|New Today]]", ""]
        self._gen(self.root / "_Dashboard.md", "\n".join(d))

        groups = [("💼 Full-Time", "full-time",
                   [j for j in new if (j.get("job_type") or "") not in ("internship", "parttime")]),
                  ("🎓 Internships / Co-ops", "internships", [j for j in new if j.get("job_type") == "internship"]),
                  ("🕒 Part-Time", "part-time", [j for j in new if j.get("job_type") == "parttime"])]
        t = [GEN_HEADER, f"# 📬 New Jobs — {today.isoformat()}", "",
             f"**{len(new)} new roles** | " + " | ".join(f"{len(g)} {short}" for _, short, g in groups), ""]
        for name, _short, g in groups:
            if not g and name != groups[0][0]:
                continue
            t += [f"## {name}", "", "| Match | Company | Role | Location | Note |",
                  "|-------|---------|------|----------|------|"]
            g = sorted(g, key=lambda j: (-(j.get("match_pct") or -1), j.get("company") or ""))
            t += [f"| {pct(j)} | {_cell(j['company'])} | {_cell((j['title'] or '')[:60])} | "
                  f"{_cell((j.get('location') or '')[:30])} | {link(j)} |" for j in g]
            t.append("")
        self._gen(self.root / "_New Today.md", "\n".join(t))

    def _gen(self, path: Path, text: str) -> None:
        text = text.rstrip("\n") + "\n"
        try:
            if path.read_text(encoding="utf-8") == text:
                return
        except OSError:
            pass
        self._write(path, text, "generated")

    # git --------------------------------------------------
    def _git(self, *args, cwd: Path, check: bool = True) -> subprocess.CompletedProcess:
        env = dict(os.environ, GIT_TERMINAL_PROMPT="0", GIT_ASKPASS="true", SSH_ASKPASS="true")
        r = subprocess.run(["git", *args], cwd=str(cwd), capture_output=True, text=True, timeout=120, env=env)
        if check and r.returncode != 0:
            raise ObsidianError(f"git {args[0]} failed: {(r.stderr or r.stdout).strip()[:300]}")
        return r

    def git_commit(self) -> str:
        """Commit the jobs folder if the vault (or the folder) is a git repo; push if it has a remote.
        Returns what happened in plain words."""
        if not self.root.is_dir():
            return "no jobs folder yet"
        try:
            r = self._git("rev-parse", "--show-toplevel", cwd=self.root, check=False)
        except (OSError, subprocess.SubprocessError) as e:
            raise ObsidianError(f"git not available: {e}") from None
        if r.returncode != 0:
            return "not a git repository"
        top = Path(r.stdout.strip())
        rel = os.path.relpath(self.root.resolve(), top.resolve())
        self._git("add", "-A", "--", rel, cwd=top)
        staged = self._git("diff", "--cached", "--quiet", "--", rel, cwd=top, check=False).returncode == 1
        did = "nothing to commit"
        if staged:
            self._git("commit", "-q", "-m", f"jobs: update {self.clock().date().isoformat()}", "--", rel, cwd=top)
            did = "committed"
        remotes = self._git("remote", cwd=top).stdout.split()
        if not remotes:
            return did
        up = self._git("rev-parse", "--abbrev-ref", "--symbolic-full-name", "@{u}", cwd=top, check=False)
        if up.returncode == 0:
            ahead = self._git("rev-list", "--count", "@{u}..HEAD", cwd=top, check=False).stdout.strip()
            if ahead == "0":
                return did
            self._git("push", "-q", cwd=top)
        else:
            self._git("push", "-q", "origin" if "origin" in remotes else remotes[0], "HEAD", cwd=top)
        return did + " and pushed"

    # doctor -----------------------------------------------
    def doctor(self) -> list:
        from ..doctor import FAIL, INFO, OK, WARN, Check
        from . import load_state, recent_conflicts
        n = "Connector: obsidian"
        if not self.vault.is_dir():
            return [Check(n, FAIL, f"vault folder not found: {self.vault}",
                          "Set connectors.obsidian.vault to your vault folder (Obsidian → 'Open folder as vault').")]
        out = []
        if not (self.vault / ".obsidian").is_dir():
            out.append(Check(n + " vault", WARN, f"{self.vault} has no .obsidian folder — is it really a vault?",
                             "Open this folder once in Obsidian, or fix connectors.obsidian.vault."))
        st = load_state(NAME)
        count = sum(1 for _ in self.notes())
        last = st.get("last_sync")
        out.append(Check(n + " notes", OK if self.root.is_dir() else INFO,
                         f"{count} note(s) in {self.oc.folder}/; last sync "
                         + (last[:16].replace("T", " ") if last else "never"),
                         "Run 'jobapp connectors sync obsidian' to write notes for the jobs you already have."))
        if self.oc.git_push:
            try:
                r = self._git("rev-parse", "--show-toplevel", cwd=self.root if self.root.is_dir() else self.vault,
                              check=False)
                ok = r.returncode == 0
            except (OSError, subprocess.SubprocessError):
                ok = False
            out.append(Check(n + " git", OK if ok else WARN, "vault is a git repository" if ok else
                             "git_push is on but the vault is not a git repository",
                             "Turn git_push off, or run 'git init' in the vault."))
        conf = recent_conflicts(NAME)
        if conf:
            c = conf[-1]
            out.append(Check(n + " conflicts", WARN,
                             f"{len(conf)} note(s) changed while JobApplication also changed the status; "
                             f"JobApplication's status was kept (latest: {c['job']} — note said '{c['note']}', "
                             f"kept '{c['kept']}')",
                             "Set the status again in the dashboard or in the note; the newer change wins."))
        return out


def effective_status(st: dict, db_status: str | None) -> str | None:
    """What the note asks for: its frontmatter status if it differs from the DB; else the Applied box."""
    s = st.get("status")
    if s in STATUSES and s != db_status:
        return s
    box = st.get("applied")
    if box is None or db_status is None:
        return s if s in STATUSES else None
    if box and db_status not in DONE_STATUSES:
        return "applied"
    if not box and db_status in DONE_STATUSES:
        return "new"
    return db_status
